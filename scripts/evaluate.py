"""Evaluator: execution match vs gold, by tier, for iterations 1 and 2.

- Iteration 1: baseline generator (v1, easy templates only).
- Iteration 2: improved generator (v2, schema-aware + validation).
- Guardrails: generated SQL is validated (validator.validate_sql);
  invalid SQL counts as incorrect, never executed. LLM is not used;
  cost is $0 for the offline generator, and latency is measured
  locally with time.perf_counter.
- Cache: iteration 2 is run twice; the second run reports cache
  hit rate. The cache file is outputs/logs/cache.json (gitignored
  in spirit — it is a run artefact, listed in MANIFEST only as logs).
- Execution match: run gold SQL and generated SQL on the SQLite
  DB, compare rows. If gold SQL has ORDER BY, compare in order;
  otherwise compare sorted rows. Floats are rounded to 2 decimals
  for comparison (amounts are money with 2 decimals).

Outputs outputs/metrics.json and outputs/logs/runs.jsonl.
Run from the project root: python3 scripts/evaluate.py
"""
import json
import sqlite3
import sys
import time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from text2sql.cache import QueryCache  # noqa: E402
from text2sql.generator import generate_sql  # noqa: E402
from text2sql.validator import ValidationError, validate_sql  # noqa: E402

DB = ROOT / "data" / "analytics.db"
GOLD = ROOT / "data" / "gold_questions.json"


def _norm_rows(rows):
    out = []
    for r in rows:
        out.append(tuple(round(v, 2) if isinstance(v, float) else v for v in r))
    return out


def _execute(con, sql):
    try:
        cur = con.execute(sql)
        return _norm_rows(cur.fetchall()), None
    except Exception as e:  # noqa: BLE001 - report DB errors as failures
        return None, str(e)


def run_iteration(con, questions, version, cache=None):
    results = []
    latencies = []
    for q in questions:
        start = time.perf_counter()
        cached = cache.get(q["question"]) if cache else None
        if cached is not None:
            gen_sql = cached
        else:
            gen_sql = generate_sql(q["question"], version=version)
            if cache and gen_sql:
                cache.put(q["question"], gen_sql)
        latency_ms = (time.perf_counter() - start) * 1000
        latencies.append(latency_ms)
        gold_rows, gold_err = _execute(con, q["gold_sql"])
        if gen_sql is None:
            results.append({**q, "generated_sql": None, "correct": False, "error": "no SQL generated", "latency_ms": round(latency_ms, 3)})
            continue
        try:
            validate_sql(gen_sql)
        except ValidationError as e:
            results.append({**q, "generated_sql": gen_sql, "correct": False, "error": f"validation: {e}", "latency_ms": round(latency_ms, 3)})
            continue
        gen_rows, gen_err = _execute(con, gen_sql)
        if gen_err:
            results.append({**q, "generated_sql": gen_sql, "correct": False, "error": gen_err, "latency_ms": round(latency_ms, 3)})
            continue
        ordered = "order by" in q["gold_sql"].lower()
        correct = (gen_rows == gold_rows) if ordered else (sorted(gen_rows) == sorted(gold_rows))
        results.append({**q, "generated_sql": gen_sql, "correct": bool(correct), "error": None, "latency_ms": round(latency_ms, 3)})
    return results, latencies


def _summarise(results):
    total = len(results)
    correct = sum(1 for r in results if r["correct"])
    by_tier = {}
    for tier in sorted({r["tier"] for r in results}):
        sub = [r for r in results if r["tier"] == tier]
        by_tier[tier] = {
            "n": len(sub),
            "correct": sum(1 for r in sub if r["correct"]),
            "accuracy": round(sum(1 for r in sub if r["correct"]) / len(sub), 4) if sub else 0.0,
        }
    return {"n": total, "correct": correct, "accuracy": round(correct / total, 4) if total else 0.0, "by_tier": by_tier}


def main():
    questions = json.loads(GOLD.read_text())
    con = sqlite3.connect(str(DB))
    try:
        iter1, lat1 = run_iteration(con, questions, version=1)
        cache = QueryCache(ROOT / "outputs" / "logs" / "cache.json")
        iter2, lat2 = run_iteration(con, questions, version=2, cache=cache)
        # Second run of iteration 2 to measure cache hits.
        cache2 = QueryCache(ROOT / "outputs" / "logs" / "cache.json")
        # Prime cache2 from the file written by the first v2 run.
        iter2_cached, lat2c = run_iteration(con, questions, version=2, cache=cache2)
        lat2c_median = sorted(lat2c)[len(lat2c) // 2] if lat2c else 0.0
        metrics = {
            "dataset": {"customers": 200, "products": 10, "orders": 2000, "db": "data/analytics.db", "data_note": "Synthetic, seed 7, generated by scripts/build_dataset.py"},
            "gold_set": {"n_questions": len(questions), "tiers": sorted({q["tier"] for q in questions})},
            "iteration_1_baseline_v1": _summarise(iter1),
            "iteration_2_improved_v2": _summarise(iter2),
            "iteration_2_cached_rerun": _summarise(iter2_cached),
            "latency_ms": {
                "iteration_1_median": round(sorted(lat1)[len(lat1) // 2], 3) if lat1 else 0.0,
                "iteration_2_median": round(sorted(lat2)[len(lat2) // 2], 3) if lat2 else 0.0,
                "iteration_2_cached_median": round(lat2c_median, 3),
            },
            "cost_usd_per_query": 0.0,
            "cost_note": "Offline rule/template generator; LLM stub is disabled and never called, so measured API cost is $0. No LLM cost is claimed.",
            "llm_api_used": False,
            "cache": cache2.stats(),
            "accuracy_threshold_for_tests": 0.80,
        }
        (ROOT / "outputs").mkdir(parents=True, exist_ok=True)
        (ROOT / "outputs" / "metrics.json").write_text(json.dumps(metrics, indent=2))
        log_path = ROOT / "outputs" / "logs" / "runs.jsonl"
        log_path.parent.mkdir(parents=True, exist_ok=True)
        with open(log_path, "w") as f:
            for r in iter1:
                f.write(json.dumps({"iteration": 1, **r}) + "\n")
            for r in iter2:
                f.write(json.dumps({"iteration": 2, **r}) + "\n")
        print(json.dumps(metrics, indent=2))
        print(f"Wrote {ROOT / 'outputs' / 'metrics.json'}")
    finally:
        con.close()


if __name__ == "__main__":
    main()
